"""各ツールのプロンプト組み立て。system指示とユーザープロンプトのペアを返す。"""

from __future__ import annotations

BASE_RULES = """あなたは日本語のプロのライターです。
共通ルール:
- 出力は本文のみ。「承知しました」などの前置きや、末尾の感想・自己言及は書かない。
- 事実が不明な数値・固有名詞・日付は捏造せず、必要なら [要確認] と明示する。
- 冗長な言い回しを避け、読み手がすぐ理解できる文にする。
- 指定された文体・文字数・構成を厳密に守る。"""


def _lines(pairs: list[tuple[str, str]]) -> str:
    """空でない項目だけを「ラベル: 値」形式で連結する。"""
    return "\n".join(f"{label}: {value}" for label, value in pairs if str(value).strip())


# --------------------------------------------------------------------------
# ブログ記事
# --------------------------------------------------------------------------
def blog(
    topic: str,
    keywords: str,
    audience: str,
    tone: str,
    length: int,
    structure: str,
    extra: str,
) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたはSEOに強いブログ編集者でもあります。
出力形式:
- Markdown。記事タイトルは `# `、見出しは `## ` / `### ` を使う。
- 導入で読者の悩みに触れ、本文で具体例を交え、最後にまとめを置く。
- 検索キーワードは不自然にならない範囲で見出しと本文に散らす。"""
    )
    prompt = _lines(
        [
            ("テーマ", topic),
            ("狙うキーワード", keywords),
            ("想定読者", audience),
            ("文体・トーン", tone),
            ("目標文字数", f"約{length}文字（±20%）"),
            ("構成の希望", structure),
            ("その他の指示", extra),
        ]
    )
    return system, "以下の条件でブログ記事を執筆してください。\n\n" + prompt


# --------------------------------------------------------------------------
# メール返信
# --------------------------------------------------------------------------
def email_reply(
    received: str,
    intent: str,
    tone: str,
    sender: str,
    recipient: str,
    length: str,
    extra: str,
) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたはビジネスメールの作成に長けたアシスタントです。
出力形式:
- 1行目に `件名: ...` を書き、空行を挟んで本文を書く。
- 宛名 → 挨拶 → 用件 → 締め → 署名欄（差出人名のみ）の順で構成する。
- 相手の質問や依頼に漏れなく回答する。断りの場合も角が立たない表現にする。
- 敬語の誤用（二重敬語・過剰敬語）に注意する。"""
    )
    prompt = _lines(
        [
            ("返信の方針・伝えたいこと", intent),
            ("宛先（相手）", recipient),
            ("差出人（自分）", sender),
            ("丁寧さ・トーン", tone),
            ("長さ", length),
            ("その他の指示", extra),
            ("--- 受信したメール本文 ---", "\n" + received),
        ]
    )
    return system, "以下のメールへの返信文を作成してください。\n\n" + prompt


# --------------------------------------------------------------------------
# 要約
# --------------------------------------------------------------------------
def summarize(text: str, style: str, length: str, focus: str) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたは要約の専門家です。
- 原文に書かれていない情報を足さない。
- 主張・根拠・結論の骨格を優先し、装飾的な表現は落とす。
- 数値や固有名詞は原文どおり正確に残す。"""
    )
    prompt = _lines(
        [
            ("要約スタイル", style),
            ("分量", length),
            ("特に知りたい観点", focus),
            ("--- 原文 ---", "\n" + text),
        ]
    )
    return system, "次の文章を要約してください。\n\n" + prompt


# --------------------------------------------------------------------------
# 校正・リライト
# --------------------------------------------------------------------------
def proofread(text: str, mode: str, tone: str, extra: str) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたは日本語校正者・編集者です。
出力形式（この見出し構成を厳守）:
## 修正後の文章
（完成形の全文）

## 主な修正点
- 「修正前」→「修正後」：理由 の形式で、重要なものを最大8件

## さらに良くするための提案
- 箇条書きで2〜4件"""
    )
    prompt = _lines(
        [
            ("処理内容", mode),
            ("目指す文体", tone),
            ("その他の指示", extra),
            ("--- 対象の文章 ---", "\n" + text),
        ]
    )
    return system, "次の文章を校正・リライトしてください。\n\n" + prompt


# --------------------------------------------------------------------------
# SNS投稿
# --------------------------------------------------------------------------
def social(platform: str, topic: str, tone: str, count: int, hashtags: bool, extra: str) -> tuple[str, str]:
    limits = {
        "X (Twitter)": "1投稿140文字以内。改行を活かし、1文目で必ず引きを作る。",
        "Instagram": "冒頭2行で惹きつけ、共感を呼ぶ語り口。絵文字は控えめに使う。",
        "LinkedIn": "ビジネス寄りの落ち着いた文体。学びや示唆で締める。",
        "Facebook": "親しみやすい語り口。200〜400文字程度。",
        "note / ブログ告知": "記事に誘導する短い紹介文。読みたくなる問いかけを入れる。",
    }
    system = (
        BASE_RULES
        + f"""

あなたはSNS運用のプロです。
プラットフォーム: {platform}
制約: {limits.get(platform, "簡潔で読みやすく。")}
出力形式:
- 案ごとに `### 案1` のような見出しを付け、本文をそのままコピーできる形で書く。
- 各案の最後に「(◯文字)」と文字数を添える。
- 案どうしで切り口（共感/実用/意外性など）を変える。"""
    )
    prompt = _lines(
        [
            ("内容・伝えたいこと", topic),
            ("トーン", tone),
            ("作成する案の数", str(count)),
            ("ハッシュタグ", "末尾に3〜5個付ける" if hashtags else "付けない"),
            ("その他の指示", extra),
        ]
    )
    return system, "以下の条件でSNS投稿文を作成してください。\n\n" + prompt


# --------------------------------------------------------------------------
# タイトル・キャッチコピー
# --------------------------------------------------------------------------
def headline(content: str, kind: str, count: int, tone: str, extra: str) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたはコピーライターです。
出力形式:
- Markdownの表。列は「No. | 案 | 狙い・切り口 | 文字数」。
- 切り口は「数字」「疑問」「意外性」「ベネフィット」「共感」などを意識して分散させる。
- 最後に `**おすすめ:** No.◯ — 理由` を1行添える。"""
    )
    prompt = _lines(
        [
            ("種類", kind),
            ("案の数", str(count)),
            ("トーン", tone),
            ("その他の指示", extra),
            ("--- 対象の内容 ---", "\n" + content),
        ]
    )
    return system, "以下の内容に対するタイトル案・キャッチコピー案を出してください。\n\n" + prompt


# --------------------------------------------------------------------------
# 翻訳
# --------------------------------------------------------------------------
def translate(text: str, direction: str, tone: str, glossary: str, with_notes: bool) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

あなたは翻訳者です。直訳ではなく、対象言語として自然な表現に整えます。
- 固有名詞・数値は正確に保持する。
- 原文の改行・箇条書き構造は維持する。"""
    )
    if with_notes:
        system += "\n出力形式: まず `## 訳文` に訳文全体、続けて `## 訳注` に判断が分かれた箇所を3件以内で説明する。"
    else:
        system += "\n出力形式: 訳文のみを出力する。解説は付けない。"

    prompt = _lines(
        [
            ("翻訳方向", direction),
            ("文体・トーン", tone),
            ("用語指定", glossary),
            ("--- 原文 ---", "\n" + text),
        ]
    )
    return system, "次の文章を翻訳してください。\n\n" + prompt


