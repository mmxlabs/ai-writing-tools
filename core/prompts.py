def refine(previous: str, instruction: str) -> tuple[str, str]:
    system = (
        BASE_RULES
        + """

既存の文章を、指示に沿って書き直します。
- 指示された点以外は元の内容・構成をできる限り保つ。
- 差分の説明はせず、書き直した全文だけを出力する。"""
    )
    prompt = f"修正指示: {instruction}\n\n--- 元の文章 ---\n{previous}"
    return system, prompt
